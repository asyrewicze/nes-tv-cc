/** Uppercases and blanks out anything the font can't draw. */
export const clean = (text: string) =>
  [...text.toUpperCase()].map(ch => (FONT[ch] ? ch : ' ')).join('')

/** Path data for `text` at (x, y), each font pixel `s` units square. */
export const glyphs = (text: string, x: number, y: number, s = 2) => {
  let d = ''
  ;[...text.toUpperCase()].forEach((ch, i) => {
    const bits = FONT[ch] ?? FONT[' ']!
    for (let k = 0; k < 15; k++) {
      if (bits[k] === '1') {
        const gx = x + i * 4 * s + (k % 3) * s
        const gy = y + Math.floor(k / 3) * s
        d += `M${gx} ${gy}h${s}v${s}h-${s}z`
      }
    }
  })
  return d
}

export const textEl = (t: string, x: number, y: number, fill: string, s = 2, cls = '') =>
  `<path ${cls ? `class="${cls}" ` : ''}fill="${fill}" d="${glyphs(t, x, y, s)}"/>`

/** "2H 40M", "40M" or "<1M". */
export const dur = (ms: number) => {
  const m = Math.floor(ms / 60000)
  if (m < 1) return '<1M'
  const h = Math.floor(m / 60)
  return h > 0 ? `${h}H ${m % 60}M` : `${m}M`
}

/** An 8-bit-style dialog frame: black box, white double border, a title tab. */
export const frame = (w: number, h: number, title: string) =>
  `<rect width="${w}" height="${h}" fill="#000"/>` +
  `<rect x="3" y="3" width="${w - 6}" height="${h - 6}" fill="none" stroke="#fcfcfc" stroke-width="2"/>` +
  `<rect x="8" y="8" width="${w - 16}" height="${h - 16}" fill="none" stroke="#7c7c7c" stroke-width="1"/>` +
  `<rect x="16" y="0" width="${title.length * 8 + 12}" height="12" fill="#000"/>` +
  textEl(title, 22, 1, '#f8b800')
